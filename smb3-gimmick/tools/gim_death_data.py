"""Convert the Gimmick! death jingle capture (tools/gim_death.lua -> out/gim_death.log)
into an APU register stream: src/PRG/gim_deathdata.asm.

Gimmick! plays sound $1F (music stop) on death, then the jingle, sound $2F, 24 frames later.
The jingle uses 2A03 square 1, square 2 and noise, plus all three Sunsoft 5B channels.
2A03 writes are replayed as captured (square/noise high-byte writes always, since they retrigger).
The 5B voices are descending sweeps; the triangle carries the loudest one each frame
(ties go to the highest pitch, which is the most recently started sweep).
5B tone f = CPU / (32 * P), triangle f = CPU / (32 * (t + 1))  =>  t = P - 1.

Stream: (register - $4000, value) pairs, $FF ends a frame, $FE ends the last frame.
"""

ROOT = '/home/olof/dev/romhacks/smb3-gimmick/'

writes = {}
state = {}
start = None
for line in open(ROOT + 'out/gim_death.log'):
    p = line.split()
    f = int(p[0])
    if p[1] == 'SFX' and p[2] == 'a=2f':
        start = f + 1
    elif p[1] == 'W':
        a, v = p[2].split('=')
        writes.setdefault(f, []).append((int(a, 16) - 0x4000, int(v, 16)))
    elif p[1].startswith('st='):
        kv = dict(x.split('=') for x in p[1:])
        vol = [int(x, 16) for x in kv['vol'].split(',')]
        state[f] = ([int(kv[c], 16) for c in 'ABC'], vol, int(kv['mix'], 16))
assert start

RETRIGGER = {0x03, 0x07, 0x0F}
TRI = {0x08, 0x09, 0x0A, 0x0B}

shadow = {}
tri_period = None
frames = []
f = start
while True:
    out = []
    for reg, val in writes.get(f, []):
        if reg in TRI or reg > 0x0F:
            continue
        if reg in RETRIGGER or shadow.get(reg) != val:
            out.append((reg, val))
            shadow[reg] = val

    periods, vols, mix = state[f + 1]
    voices = [(vols[i], -periods[i], periods[i]) for i in range(3) if not mix & (1 << i) and vols[i]]
    if voices:
        p = max(voices)[2]
        if tri_period is None:
            out.append((0x08, 0xFF))
        if p != tri_period:
            t = p - 1
            out += [(0x0A, t & 0xFF), (0x0B, 0xF8 | t >> 8)]
        tri_period = p
    elif tri_period is not None:
        out.append((0x08, 0x80))
        tri_period = None

    frames.append(out)
    silent = (shadow.get(0x00, 0) & 0x0F) == 0 and (shadow.get(0x04, 0) & 0x0F) == 0 \
        and (shadow.get(0x0C, 0) & 0x0F) == 0 and tri_period is None
    if silent and f > start + 8:
        break
    f += 1

data = []
for i, fr in enumerate(frames):
    for reg, val in fr:
        data += [reg, val]
    data.append(0xFE if i == len(frames) - 1 else 0xFF)


def rows(d):
    return '\n'.join('\t.byte ' + ', '.join('$%02X' % b for b in d[i:i + 16]) for i in range(0, len(d), 16))


with open(ROOT + 'src/PRG/gim_deathdata.asm', 'w') as fo:
    fo.write('; Generated by tools/gim_death_data.py from the Gimmick! death jingle capture\n')
    fo.write('GimDeath_Data:\n' + rows(data) + '\n')
print(len(frames), 'frames,', len(data), 'bytes')
