#!/usr/bin/env python3
"""Writes src/PRG/gim_levelfix.asm: tiles changed in levels Yumetaro can't otherwise get through.

Mario's running jump clears gaps and walls that Yumetaro's can't. Each entry names a level's layout,
and the tiles to set as it loads: (column, row, tile), columns counted across the whole level.
"""
import os

FIXES = [
    # 6-7's end: a wall of 6 tiles, more than even a jump from the star clears. Steps cut into its left side,
    # and the hidden block before it gone, which he hit his head on going up them
    ("W607_EndL", 12, "6-7's end", [(2, 22, 0x80), (3, 20, 0x80), (3, 21, 0x80), (3, 22, 0x80), (4, 20, 0x80)]),
    # World 7's first piranha stage: pipes 5 tiles tall. A block before each
    ("W7I1L", 5, "World 7 plant 1", [(8, 23, 0xB8), (9, 23, 0xB8), (8, 24, 0x99), (9, 24, 0x99),
                                      (16, 23, 0xB8), (17, 23, 0xB8), (16, 24, 0x99), (17, 24, 0x99)]),
    # World 7's second fortress: from the stairs to the first pipe is 7 tiles and up. A ledge between
    ("W7F2L", 2, "World 7 fortress 2", [(8, 22, 0xE4), (9, 22, 0xE4), (16, 24, 0xE4), (68, 24, 0xE4)]),
    # 5-8: a gap of 5 from the start. The ledge a tile longer
    ("W508L", 13, "5-8", [(9, 24, 0xD5), (9, 25, 0xEC), (10, 24, 0xD6), (10, 25, 0xED),
                       (24, 25, 0xD1), (25, 25, 0xD3), (24, 26, 0xE8), (25, 26, 0xEA),
                       (45, 25, 0xD1), (45, 26, 0xE8)]),
    # 7-8: a pipe of 5 tiles. A step before it, on what were hills in the background
    ("W708L", 1, "7-8", [(28, 23, 0x63), (29, 23, 0x63), (47, 24, 0x63)]),
    # World 5's fortress: a gap of 5 over lava. An island in it
    ("W5F1L", 2, "World 5 fortress", [(14, 25, 0xE4)]),
    # World 4's second fortress: 4 tiles across and 3 up
    ("W4F2L", 2, "World 4 fortress 2", [(27, 21, 0x5B), (28, 21, 0x5B), (46, 22, 0x5B),
                                         (59, 21, 0x5B), (67, 21, 0x5B)]),
    # 6-4: a gap of 5 from the start. The ledge a tile or two longer
    ("W604L", 12, "6-4", [(5, 25, 0x8F), (5, 26, 0x53), (6, 25, 0x90), (6, 26, 0x54)]),
    # World 7's second plant stage: 4 up to a pipe
    ("W7I2L", 5, "World 7 plant 2", [(10, 22, 0xB8), (11, 22, 0xB8)]),
    # 4-6: a gap of 6. An island in it
    ("W46AL", 1, "4-6", [(32, 26, 0x55), (33, 26, 0x57)]),
    ("W46BL", 1, "4-6 dark", [(32, 26, 0x55), (33, 26, 0x57)]),
]


def main():
    out = ["; Generated by tools/gen_levelfix.py", "", "Gim_LevelFixes:"]
    for label, tileset, name, tiles in FIXES:
        out.append("\t; " + name)
        out.append("\t.word %s" % label)
        out.append("\t.byte %d, %d" % (tileset, len(tiles)))
        for c, r, t in tiles:
            off = (c // 16) * 0x1B0 + r * 16 + c % 16
            out.append("\t.byte $%02X, $%02X, $%02X" % (off >> 8, off & 0xFF, t))
    out.append("\t.word $0000")
    root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
    with open(os.path.join(root, "src", "PRG", "gim_levelfix.asm"), "w") as f:
        f.write("\n".join(out) + "\n")


main()
