import os
from nes import load_rom, tile_pixels, encode_tile

ROOT = os.path.join(os.path.dirname(__file__), '..')
_, gchr = load_rom(os.path.join(ROOT, 'Gimmick! (Japan).nes'))
_, schr = load_rom(os.path.join(ROOT, 'Super Mario Bros III.nes'))

GIM_PAGES = (0, 101, 102, 103)
SMB_BANK = 120

LOGO = [
    "01 01 92 a2 b2 01 40 50 60 70 43 53 63 73 46 56 66 c0 d0 e0 eb c8 d8 01",
    "01 01 93 a3 b3 01 41 51 61 71 44 54 64 74 47 57 67 c1 d1 e1 f1 c9 d9 01",
    "01 84 94 a4 b3 88 42 52 62 72 45 55 65 75 6e 01 01 01 d2 01 f2 ca da 01",
    "01 85 95 a5 b5 89 82 9a 01 ad bd ba a0 b0 aa c2 e2 c3 d3 fa 01 cb db 01",
    "01 86 96 a6 b6 8a a1 9b ab ae be bb a1 b1 b4 80 e3 c4 d4 e4 f4 cc dc 01",
    "01 87 97 a7 b7 8b a1 9c ac af bf bc a1 81 91 90 01 c5 d5 e5 01 cd dd 01",
    "01 01 98 a8 b8 8c a1 9d 01 ef bf bc a1 81 8e 9e ea c6 d6 e6 f6 ce de 01",
    "01 01 99 a9 b9 8d 83 fb 01 ec fc ed fd ee fe 9f f0 c7 d7 e7 f7 cf df 01",
    "01 e8 f3 f3 48 f3 f3 f3 f3 58 f3 f3 f3 f3 68 f3 f3 f3 f3 78 f3 f3 f8 01",
    "ff f5 f5 f5 49 f5 f5 f5 f5 59 f5 f5 f5 f5 69 f5 f5 f5 f5 79 f5 f5 f5 ff",
]
LOGO_ROW = 3
LOGO_COL = 4

# Gimmick colours 0 black, 1 dark grey, 2 light grey, 3 white.
# Palette 1 is black/grey/white; the bottom row shares attribute blocks with the 3 and uses palette 3 (black/glow/white).
MAP_BODY = (1, 2, 2, 3)
MAP_BOTTOM = (1, 1, 1, 3)

FREE = (list(range(0x30, 0x3F)) + list(range(0x40, 0x4F)) + list(range(0x50, 0x5B)) + [0x5B]
        + list(range(0x60, 0x6B)) + [0x6B] + list(range(0x70, 0x7C)) + list(range(0x7D, 0xC9))
        + list(range(0xD0, 0xD9)) + list(range(0xE0, 0xE6)) + [0xE8] + list(range(0xF0, 0xF6)))

ATTR = [0xF0] * 8 + [0x2A, 0x8A, 0x66, 0x55, 0x55, 0x99, 0xA2, 0xA8] \
    + [0xAA, 0x55, 0x55, 0x55, 0x55, 0x55, 0x55, 0xA9] + [0xA8, 0xA6, 0xA5, 0xED, 0x77, 0xB5, 0xA5, 0xAA]

ROW12_RIGHT = [0x04, 0x05, 0x06, 0x07]


def gim_tile(t):
    page = GIM_PAGES[t >> 6]
    return tile_pixels(gchr, page * 1024 + (t & 0x3F) * 16)


def set_attr(attr, row, col, pal):
    i = (row // 4) * 8 + col // 4
    sh = ((row % 4) // 2) * 4 + ((col % 4) // 2) * 2
    attr[i] = (attr[i] & ~(3 << sh)) | (pal << sh)


def main():
    chr_data = bytearray(schr[SMB_BANK * 1024:(SMB_BANK + 4) * 1024])
    slots = {}
    free = iter(FREE)
    rows = []
    for r, line in enumerate(LOGO):
        cmap = MAP_BOTTOM if r == len(LOGO) - 1 else MAP_BODY
        out = []
        for t in (int(x, 16) for x in line.split()):
            pix = [[cmap[v] for v in row] for row in gim_tile(t)]
            enc = bytes(encode_tile(pix))
            if enc not in slots:
                slot = next(free)
                slots[enc] = slot
                chr_data[slot * 16:slot * 16 + 16] = enc
            out.append(slots[enc])
        rows.append(out)
    print('logo tiles: %d of %d free slots' % (len(slots), len(FREE)))

    for i in range(4):
        with open(os.path.join(ROOT, 'src', 'CHR', 'chr%03d.bin' % (SMB_BANK + i)), 'wb') as f:
            f.write(chr_data[i * 1024:(i + 1) * 1024])

    attr = ATTR[:]
    for r in range(len(LOGO)):
        for c in range(0, len(LOGO[0].split()), 2):
            row = LOGO_ROW + r
            pal = 3 if r == len(LOGO) - 1 else 1
            set_attr(attr, row, LOGO_COL + c, pal)

    lines = []
    for r, out in enumerate(rows):
        row = LOGO_ROW + r
        full = [0x5C] * LOGO_COL + out + [0x5C] * (32 - LOGO_COL - len(out))
        if r == len(LOGO) - 1:
            full[28:32] = ROW12_RIGHT
        lines.append('TitleScreen_LogoLine%02d:' % (row + 1))
        lines.append('\tvaddr $%04X' % (0x2000 + row * 32))
        lines.append('\t.byte $20')
        for k in range(0, 32, 16):
            lines.append('\t.byte ' + ', '.join('$%02X' % b for b in full[k:k + 16]))
        lines.append('\t.byte $00')
        lines.append('')
    lines.append('TitleScreen_LogoAttr1:')
    lines.append('\tvaddr $23C0')
    lines.append('\t.byte $20')
    for k in range(0, 32, 16):
        lines.append('\t.byte ' + ', '.join('$%02X' % b for b in attr[k:k + 16]))
    lines.append('\t.byte $00')
    with open(os.path.join(ROOT, 'src', 'PRG', 'title_logo.asm'), 'w') as f:
        f.write('; Generated by tools/build_title.py\n\n' + '\n'.join(lines) + '\n')


main()
