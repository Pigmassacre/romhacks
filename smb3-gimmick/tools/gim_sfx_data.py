"""Convert Gimmick! 5B channel C sound effect captures (tools/gim_sfx2.lua) into
SMB3 square 1 frame data: src/PRG/gim_sfxdata.asm.

Per frame: GimSnd_Ctl = volume << 4 | timer high (0 = end), GimSnd_Lo = timer low.
5B tone f = CPU / (32 * P), 2A03 square f = CPU / (16 * (t + 1))  =>  t = 2P - 1.
5B volume is ~3 dB per step; mapped so Gimmick volume 10 -> 12.
"""
import math

ROOT = '/home/olof/dev/romhacks/smb3-gimmick/'
SOUNDS = [('JUMP', 0x0D, 32), ('CHARGE', 0x10, 70), ('THROW', 0x13, 24), ('BOUNCE', 0x15, 22)]

seq = {}
cur = None
for line in open(ROOT + 'out/gim_sfx2.log'):
    p = line.split()
    if p[0] == 'ID':
        cur = int(p[1], 16)
        seq[cur] = []
        continue
    seq[cur].append((int(p[1][2:], 16), int(p[2][2:], 16)))

ctl = [0]
lo = [0]
starts = []
for name, gid, length in SOUNDS:
    frames = seq[gid][1:length + 1]
    assert all(v for _, v in frames), name
    starts.append(len(ctl))
    for period, vol in frames:
        t = 2 * period - 1
        assert 8 <= t < 0x800, (name, period)
        v = round(12 * math.pow(2, (vol - 10) / 2))
        ctl.append(v << 4 | t >> 8)
        lo.append(t & 0xFF)
    ctl.append(0)
    lo.append(0)
assert len(ctl) <= 256

def rows(data):
    out = []
    for i in range(0, len(data), 16):
        out.append('\t.byte ' + ', '.join('$%02X' % b for b in data[i:i + 16]))
    return '\n'.join(out)

with open(ROOT + 'src/PRG/gim_sfxdata.asm', 'w') as f:
    f.write('; Generated by tools/gim_sfx_data.py from Gimmick! sound captures\n')
    f.write('GimSnd_Start:\n\t.byte ' + ', '.join('$%02X' % s for s in starts) + '\n\n')
    f.write('GimSnd_Ctl:\n' + rows(ctl) + '\n\n')
    f.write('GimSnd_Lo:\n' + rows(lo) + '\n')
print(len(ctl), 'frames incl. terminators')
