#!/usr/bin/env python3
"""Turn a design from the title editor (tools/title_editor.html) into src/title.asm.

    python3 tools/title_import.py design.json ppu_dump

design.json is what the editor saves. ppu_dump is 16 KB of the PPU's memory on
Castlevania's own title screen. Castlevania draws its title as ever and the hack
patches it (see PutTitle), so only what differs goes in the source: the new
tiles, the changed cells of the name table, the attributes and the palettes.
Tiles Castlevania already has keep their numbers, because the flashing PUSH START
KEY writes those numbers to the screen itself.
"""
import json
import os
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TILES = 0x1000
NAMES = 0x2000
FONT = 0xD0                 # the status bar's font, from here on: stages rely on it


def db(rows):
    return "".join("        .db " + ",".join("$%02X" % b for b in r) + "\n" for r in rows)


def main():
    d = json.load(open(sys.argv[1]))
    d = d.get("data", d)
    ppu = open(sys.argv[2], "rb").read()
    tiles = [bytes.fromhex(t) for t in d["tiles"]]
    cells = bytes.fromhex(d["nametable"])
    attrs = bytes.fromhex(d["attributes"])
    was = ppu[NAMES:NAMES + 960]
    old = [ppu[TILES + i * 16:TILES + i * 16 + 16] for i in range(256)]

    # the same tile where it already is, which also keeps those numbers in use
    keep = {i: was[i] for i in range(960) if old[was[i]] == tiles[cells[i]]}
    used = set(keep.values())
    known = {}
    for i in sorted(used | set(range(FONT, 256))):   # (the font's tiles all stay)
        known.setdefault(old[i], i)
    free = [i for i in sorted(set(was) - used) if i < FONT]
    new, final, changed = [], {}, []
    for i in range(960):
        if i in keep:
            continue
        t = tiles[cells[i]]
        if t not in known:
            if not free:
                sys.exit("no free tile numbers left")
            known[t] = free.pop(0)
            new.append((known[t], t))
        changed.append((i, known[t]))
    screen = bytearray(was)
    for i, n in changed:
        screen[i] = n
    # checksum for tests/t_titlelogo.lua: the name table and attributes on screen
    total = sum(screen) + sum(attrs)

    pals = d["palettes"]
    out = ["; Generated by tools/title_import.py from the title editor's design. Don't edit.",
           "; checksum %d" % total, ""]
    out.append("TitleTiles:\n")
    for n, t in new:
        out.append(db([[n], t]))
    out.append("TITLE_TILES = %d\n" % len(new))
    out.append("TitleCells:\n")
    for i, n in changed:
        a = NAMES + i
        out.append(db([[a >> 8, a & 255, n]]))
    out.append("TITLE_CELLS = %d\n" % len(changed))
    out.append("TitleAttrs:\n")
    out.append(db([attrs[i:i + 16] for i in range(0, 64, 16)]))
    # main.asm writes these over the title's palettes
    flat = pals[0] + [d["backdrop"]] + pals[1] + [d["backdrop"]] + pals[2] + [d["backdrop"]] + pals[3]
    out.append("".join("TITLE_PAL%d = $%02X\n" % (i, c) for i, c in enumerate(flat)))
    open(os.path.join(REPO, "src", "title.asm"), "w").write("\n".join(out))
    print("%d new tiles, %d changed cells; checksum %d" % (len(new), len(changed), total))


main()
